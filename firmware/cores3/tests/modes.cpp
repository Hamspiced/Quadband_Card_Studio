#include "workbench.hpp"
#include <cassert>

int main() {
    using namespace qb;
    ModeBroker modes;
    assert(modes.mode() == WorkMode::Home);
    assert(!modes.remote_allowed() && !modes.local_allowed());
    assert(modes.request(WorkMode::Connected, false, false) == ModeRequest::Queued);
    assert(!modes.remote_allowed());
    assert(!modes.complete(false));
    assert(modes.complete(true) && modes.remote_allowed());
    assert(modes.request(WorkMode::Standalone, true, true) == ModeRequest::Confirm);
    assert(modes.mode() == WorkMode::Connected && !modes.pending());
    assert(modes.request(WorkMode::Standalone, true, true, true) == ModeRequest::Queued);
    assert(!modes.remote_allowed() && !modes.local_allowed());
    assert(modes.request(WorkMode::Home, false, false) == ModeRequest::Busy);
    assert(!modes.complete(false));
    assert(modes.complete(true) && modes.local_allowed());
    assert(modes.request(WorkMode::Standalone, false, true) == ModeRequest::Unchanged);
    assert(modes.request(WorkMode::Connected, false, true) == ModeRequest::Confirm);
    assert(modes.local_allowed());
    assert(modes.request(WorkMode::Home, false, false, true) == ModeRequest::Queued);
    assert(modes.complete(true) && !modes.remote_allowed() && !modes.local_allowed());
    assert(std::string(mode_owner(modes.mode())) == "none");
    Session session; session.nonce = 42;
    std::array<Slot, 3> slots;
    for (auto& slot : slots) slot.present = true;
    Frame command; command.session = 42; command.id = 1; command.channel = 1; command.op = 16; command.generation = 1;
    assert(modes.admit(session, command, false, slots) == NOT_AUTHORIZED);
    assert(modes.admit(session, command, true, slots) == BUSY && session.pending == 0);
    assert(modes.admit(session, command, true, slots) == BAD_SESSION);
    assert(modes.request(WorkMode::Connected, false, false) == ModeRequest::Queued);
    assert(modes.complete(true));
    command.id = 2;
    assert(modes.admit(session, command, true, slots) == OK && session.pending == 2);
    assert(modes.request(WorkMode::Standalone, true, true, true) == ModeRequest::Queued);
    command.id = 3;
    assert(modes.admit(session, command, true, slots) == BUSY && session.pending == 2);
    assert(!modes.complete(false));
    session.pending = 0;
    assert(modes.complete(true));
    command.id = 4;
    assert(modes.admit(session, command, true, slots) == BUSY && session.pending == 0);
    Frame control; control.session = 42; control.id = 5; control.op = 2;
    assert(modes.admit(session, control, true, slots) == OK);
    session.pending = 9;
    assert(!modes.cancel_remote(session, 0) && !session.cancelled);
    assert(!modes.cancel_remote(session, 9) && !session.cancelled);
    modes.release_failed();
    assert(modes.mode() == WorkMode::Home && !modes.pending());
    assert(!modes.remote_allowed() && !modes.local_allowed());
    assert(modes.request(WorkMode::Connected, false, false) == ModeRequest::Queued);
    assert(modes.complete(true));
    assert(!modes.cancel_remote(session, 8));
    assert(modes.cancel_remote(session, 9) && session.cancelled);

    TouchGate touches;
    UiSnapshot screen;
    assert(!touches.permit(screen, true, true));
    assert(!touches.permit(screen, false, false));
    assert(touches.permit(screen, true, true));
    assert(pairing_reply_matches(true, 123, 123));
    assert(!pairing_reply_matches(true, 123, 124));
    assert(!pairing_reply_matches(true, 0, 123));
    assert(pairing_reply_matches(false, 0, 123));
    assert(!pairing_reply_matches(false, 123, 124));
    Bytes acknowledgement{0x11, 0xef, 3, 0xe9, 0, 0x68, 0, 0, 0, 0};
    Bytes readback{0x11, 0xef, 3, 0xea, 0, 0x68, 0, 1, 0, 0, 0};
    assert(release_mode_verified(acknowledgement, readback, 0));
    assert(!release_mode_verified(acknowledgement, readback, 1));
    acknowledgement[5] = 1;
    assert(!release_mode_verified(acknowledgement, readback, 0));
    acknowledgement[5] = 0x68; readback.resize(9);
    assert(!release_mode_verified(acknowledgement, readback, 0));
    assert(!touches.permit(screen, true, true));
    assert(!touches.permit(screen, false, false));
    screen.pairing_pending = true; screen.pairing_code = 123456; screen.pairing_challenge = 1;
    assert(!touches.permit(screen, true, true));
    assert(!touches.permit(screen, false, true));
    assert(!touches.permit(screen, false, false));
    assert(touches.permit(screen, true, true));
    screen.pairing_challenge = 2;
    assert(!touches.permit(screen, true, true));
    assert(!touches.permit(screen, false, false));
    assert(touches.permit(screen, true, true));
    screen.pairing_pending = false; screen.confirm_usb = true;
    assert(!touches.permit(screen, true, true));
    assert(!touches.permit(screen, false, false));
    assert(touches.permit(screen, true, true));
    TouchGate reviews;
    UiSnapshot review;
    assert(!reviews.permit(review, false, false));
    assert(!reviews.permit(review, false, false));
    review.local.review = true; review.local.review_token = 7;
    assert(!reviews.permit(review, true, true));
    assert(!reviews.permit(review, false, false));
    assert(reviews.permit(review, true, true));
    review.local.review_token = 8;
    assert(!reviews.permit(review, true, true));
}
